let currentLang = 'en';

/** Set the active language (falls back to English for unknown values). */
export function setLanguage(lang) {
  currentLang = STRINGS[lang] ? lang : 'en';
  return currentLang;
}

export function getLanguage() {
  return currentLang;
}

/**
 * Translate a key. `{name}` placeholders are replaced from `vars`.
 * Missing keys fall back to English, then to the key itself.
 */
export function t(key, vars = {}) {
  const table = STRINGS[currentLang] || STRINGS.en;
  let s = table[key] !== undefined ? table[key] : (STRINGS.en[key] !== undefined ? STRINGS.en[key] : key);
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll('{' + k + '}', String(v));
  }
  return s;
}

/** Document direction for the active language. */
export function languageDirection(lang = currentLang) {
  return lang === 'fa' ? 'rtl' : 'ltr';
}

/** Pluralization helper for the item/items pattern (FA has no plural suffix). */
export function itemsKey(n) {
  return currentLang === 'fa' ? 'items' : (n === 1 ? 'item' : 'items');
}
